const revealObserver=new IntersectionObserver(entries=>{
  entries.forEach(entry=>{
    if(entry.isIntersecting){entry.target.classList.add("visible");revealObserver.unobserve(entry.target);}
  });
},{threshold:.08,rootMargin:"0px 0px -4% 0px"});
document.querySelectorAll(".reveal").forEach(el=>revealObserver.observe(el));

const progress=document.getElementById("progress");
window.addEventListener("scroll",()=>{
  const max=document.documentElement.scrollHeight-innerHeight;
  progress.style.width=`${max ? scrollY/max*100 : 0}%`;
},{passive:true});

const menuButton=document.getElementById("menuButton");
const mobileMenu=document.getElementById("mobileMenu");
function setMenu(open){
  mobileMenu.classList.toggle("open",open);
  document.body.classList.toggle("menu-open",open);
  menuButton.setAttribute("aria-expanded",String(open));
  mobileMenu.setAttribute("aria-hidden",String(!open));
}
menuButton.addEventListener("click",()=>setMenu(!mobileMenu.classList.contains("open")));
mobileMenu.querySelectorAll("a").forEach(a=>a.addEventListener("click",()=>setMenu(false)));


// Very subtle hero drift without heavy animation.
if(!matchMedia("(prefers-reduced-motion: reduce)").matches){
  const heroImage=document.querySelector(".hero-image");
  window.addEventListener("scroll",()=>{
    if(scrollY<innerHeight*1.2) heroImage.style.transform=`scale(1.04) translateY(${scrollY*.055}px)`;
  },{passive:true});
}


// Warn only if the original Wix assets are genuinely unavailable.
(function(){
  const warning = document.getElementById("assetWarning");
  const probe = new Image();
  probe.onload = () => { if (warning) warning.hidden = true; };
  probe.onerror = () => { if (warning) warning.hidden = false; };
  probe.src = "https://static.wixstatic.com/media/5e11b3_0b10bbd4b562434a9aaf1ec474ce1dc4f000.jpg";
})();

// Graceful fallback for archive images.
document.addEventListener("error", (e) => {
  if (e.target && e.target.tagName === "IMG" && e.target.closest(".archive-item")) {
    e.target.closest(".archive-item").style.display = "none";
  }
}, true);

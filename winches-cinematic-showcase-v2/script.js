const creditList = document.getElementById("creditList");
function renderCredits(type="stunt"){
  const data = type === "stunt" ? stuntCredits : wirecamCredits;
  creditList.innerHTML = data.map(([year,title,role]) => `
    <article class="credit-row">
      <span class="year">${year}</span>
      <h3>${title}</h3>
      <p>${role}</p>
      <span class="mark">↗</span>
    </article>`).join("");
}
renderCredits();

document.querySelectorAll(".credit-tab").forEach(btn=>{
  btn.addEventListener("click",()=>{
    document.querySelectorAll(".credit-tab").forEach(b=>b.classList.remove("active"));
    btn.classList.add("active");
    renderCredits(btn.dataset.credit);
  });
});

